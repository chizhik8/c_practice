#include <stdio.h>

/*
    #include — це команда препроцесора C підключення файлів. Вона виконується ще до компіляції програми. 
    Препроцесор знаходить файл і умовно підставляє його вміст. 
    Існують два основні способи підключення: <...> і "...". Кутові дужки використовують переважно для системних і стандартних заголовків. 
    Подвійні лапки використовують для власних заголовних файлів. 
    І ще одна важлива деталь: після #include не ставиться ;
    Процес приблизно такий: #include → препроцесор → компілятор → компонувальник → програма
*/

/*
    У stdio.h (standard input/output) оголошені функції стандартного введення та виведення:
    `printf()` Виводить форматований текст у консоль. 
    `scanf()` Зчитує форматовані дані з клавіатури.
    `getchar()` Зчитує один символ.
    `putchar()` Виводить один символ.
    `puts()` Виводить рядок і автоматично додає `\n`. 
    `fgets()` Безпечніше зчитує рядок, зокрема з пробілами. 
    `fopen()` Відкриває файл. 
    `fclose()` Закриває файл. 
    `fprintf()` Записує форматований текст у файл. 
    `fscanf()` Зчитує форматовані дані з файлу. 
    `fputs()` Записує рядок у файл. 
    `fgetc()` Зчитує один символ із файлу. 
    `fputc()` Записує один символ у файл. 
    `remove()` Видаляє файл. 
    `rename()` Перейменовує файл. 
*/

int hello () {
    printf("Hello World!\n"); // \n — спеціальний символ нового рядка
    printf("Full Name: Billy Bob\nAge: 100\n");
    puts("Hello World! Hello World!");
    return 0;
};

/*
    У мові C символи на кшталт \n називаються керівними (escape) послідовностями. 
    Вони починаються зі зворотної похилої риски \ та позначають символи, які важко або неможливо безпосередньо записати в тексті.
    `\n` Перехід на новий рядок
    `\t` Горизонтальна табуляція
    `\r` Повернення курсора на початок поточного рядка
    `\b` Повернення на один символ назад
    `\a` Звуковий сигнал, якщо термінал його підтримує
    `\f` Перехід на нову сторінку
    `\v` Вертикальна табуляція
    `\\` Символ зворотної похилої риски `\`
    `\"` Подвійні лапки `"`
    `\'` Одинарна лапка `'`
    `\?` Знак питання `?`
    `\0` Нульовий символ із кодом `0`
*/

int calc () {
    printf("Today I'm %d years old and next year I'm going to be %d years old\n", 20, 21);
    printf("%d + %d = %d \n", 5, 2, 5+2);
    printf("%d - %d = %d \n", 5, 2, 5-2);
    printf("%d * %d = %d \n", 5, 2, 5*2);
    printf("%d / %d = %d \n", 5, 2, 5/2);
    printf("%d %% %d = %d \n", 5, 2, 5%2);
    return 0;
};

/*
    Специфікатор формату — це позначка, яка повідомляє функціям, якого типу дані потрібно вивести або зчитати.
        int age = 20;
        printf("Мені %d років\n", age);
    Тут %d замінюється значенням змінної age.
    Тип змінної повинен відповідати специфікатору.
    
    Змінна — це іменована ділянка пам’яті, у якій програма зберігає значення.
    Тип визначає:
        - які значення можна зберігати;
        - скільки пам’яті приблизно займає змінна;
        - які операції з нею дозволені;
        - який специфікатор формату потрібно використовувати.
    Головне правило: тип змінної потрібно вибирати відповідно до даних.

    > Цілі числа - int (тип) - %d (специфікатор)
    для відносно невеликих цілих чисел - short - %hd
    більші цілі числа - long - %ld
    для дуже великих цілих чисел: - long long - %lld

    > Символьний тип - char - %c
    char symbol = '7'; — символ
    int number = 7; — число

    > Дробові типи - float - %f
*/

int main()
{
    hello();
    calc();
    return 0; // повідомляє операційній системі, що програма завершилася успішно
}
